/**
 * Generate test/vectors.json from the BACKEND's real signer.
 *
 * The parity test used to require ../../backend/dist directly, which cannot
 * work once this package lives in its own repository. Freezing real signatures
 * into vectors keeps the guarantee that matters — that this node's verifier
 * agrees with the service's signer — without the cross-repo path.
 *
 * Re-run from the monorepo if the signing scheme ever changes:
 *   cd backend && npm run build
 *   cd ../n8n-nodes-slide && node scripts-gen-vectors.js
 */
const fs = require('fs');
const backend = require('./test/../../backend/dist/src/outbound-webhooks/utils/webhook-signature.util.js');

// Fixed timestamp so the vectors are deterministic and reviewable in a diff.
const TIMESTAMP = 1755683472;

const cases = [
  {
    label: 'contact.created',
    secret: 'whsec_TestVectorSecretDoNotUseInProduction_0001',
    body: JSON.stringify({
      id: 'evt_9f2c4b1e', type: 'contact.created',
      createdAt: '2026-08-20T10:11:12.000Z', accountId: 'org_9f2c4b1e',
      livemode: true, data: { contact: { id: 'ct_1', name: 'Priya Sharma' }, source: 'widget' },
    }),
  },
  {
    label: 'unicode and punctuation in the body',
    secret: 'whsec_TestVectorSecretDoNotUseInProduction_0002',
    body: JSON.stringify({
      id: 'evt_unicode', type: 'whatsapp.message.received',
      data: { text: 'Namaste 🙏 — do you ship to Pune?', from: '+919876543210' },
    }),
  },
  {
    label: 'empty data object',
    secret: 'whsec_TestVectorSecretDoNotUseInProduction_0003',
    body: JSON.stringify({ id: 'evt_empty', type: 'voice.call.completed', data: {} }),
  },
];

const vectors = cases.map((c) => ({
  ...c,
  timestamp: TIMESTAMP,
  // Produced by the service's own signer, not reimplemented here.
  signature: backend.signWebhookPayload(c.body, c.secret, TIMESTAMP),
}));

fs.writeFileSync(
  'test/vectors.json',
  JSON.stringify(
    {
      _comment:
        'GENERATED by scripts-gen-vectors.js from the Slide backend signer. Do not hand-edit. These prove this node verifies signatures the service actually produces.',
      _generatedFrom: 'backend/src/outbound-webhooks/utils/webhook-signature.util.ts',
      vectors,
    },
    null,
    2,
  ) + '\n',
);

console.log(`wrote test/vectors.json — ${vectors.length} vectors from the real backend signer`);
